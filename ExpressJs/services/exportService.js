import PDFDocument from 'pdfkit';

/**
 * Generate a professional bulk appointments PDF report stream
 */
export const buildAppointmentsPdfStream = (appointments = [], filters = {}, adminUser = {}) => {
  const doc = new PDFDocument({
    margin: 40,
    size: 'A4',
    bufferPages: true,
    info: {
      Title: 'HealPoint Clinical Appointments Report',
      Author: 'HealPoint Healthcare Management System',
      Subject: 'Appointment Administration Report'
    }
  });

  // Colors
  const brandNavy = '#111C2F';
  const brandTeal = '#087F72';
  const textDark = '#172033';
  const textMuted = '#64748B';
  const borderLight = '#E2E8F0';
  const zebraBg = '#F8FAFC';

  // 1. Header Banner
  doc.rect(40, 40, 515, 60).fill(brandNavy);
  
  // Teal accent line
  doc.rect(40, 100, 515, 4).fill(brandTeal);

  doc.fillColor('#FFFFFF')
     .fontSize(16)
     .font('Helvetica-Bold')
     .text('HEALPOINT HEALTHCARE SYSTEMS', 55, 52);

  doc.fontSize(10)
     .font('Helvetica')
     .fillColor('#94A3B8')
     .text('Clinical Appointment Administration & Governance Report', 55, 74);

  doc.fontSize(8)
     .fillColor('#A7F3D0')
     .text(`Generated on: ${new Date().toLocaleString()}`, 380, 56, { align: 'right', width: 160 });

  doc.text(`Generated by: ${adminUser.email || 'admin@healpoint.com'}`, 380, 70, { align: 'right', width: 160 });

  // 2. Filter Summary Box
  let y = 120;
  doc.rect(40, y, 515, 45).fillAndStroke('#F1F5F9', borderLight);

  doc.fillColor(textDark)
     .fontSize(9)
     .font('Helvetica-Bold')
     .text('APPLIED REPORT FILTERS & PARAMETERS', 50, y + 8);

  const statusLabel = filters.status || 'ALL STATUSES';
  const specialtyLabel = filters.specialty || 'ALL SPECIALTIES';
  const searchLabel = filters.search ? `"${filters.search}"` : 'NONE';
  const dateRangeLabel = (filters.startDate || filters.endDate) 
    ? `${filters.startDate || 'Start'} to ${filters.endDate || 'Present'}`
    : 'ALL RECORDED DATES';

  doc.fontSize(8)
     .font('Helvetica')
     .fillColor(textMuted)
     .text(`Status Filter: `, 50, y + 24, { continued: true })
     .font('Helvetica-Bold').fillColor(textDark).text(`${statusLabel}   |   `, { continued: true })
     .font('Helvetica').fillColor(textMuted).text(`Specialty: `, { continued: true })
     .font('Helvetica-Bold').fillColor(textDark).text(`${specialtyLabel}   |   `, { continued: true })
     .font('Helvetica').fillColor(textMuted).text(`Date Range: `, { continued: true })
     .font('Helvetica-Bold').fillColor(textDark).text(`${dateRangeLabel}`);

  doc.font('Helvetica')
     .fillColor(textMuted)
     .text(`Search Term: `, 50, y + 34, { continued: true })
     .font('Helvetica-Bold').fillColor(textDark).text(`${searchLabel}   |   `, { continued: true })
     .font('Helvetica').fillColor(textMuted).text(`Matching Records: `, { continued: true })
     .font('Helvetica-Bold').fillColor(brandTeal).text(`${appointments.length} Bookings`);

  // 3. Table Header
  y = 180;
  const colX = { id: 45, patient: 85, doctor: 195, date: 310, type: 395, status: 455, fee: 510 };
  
  const drawTableHeader = (posY) => {
    doc.rect(40, posY, 515, 20).fill(brandTeal);
    doc.fillColor('#FFFFFF')
       .fontSize(8)
       .font('Helvetica-Bold')
       .text('ID', colX.id, posY + 6)
       .text('PATIENT', colX.patient, posY + 6)
       .text('DOCTOR & SPECIALTY', colX.doctor, posY + 6)
       .text('DATE & TIME', colX.date, posY + 6)
       .text('MODE', colX.type, posY + 6)
       .text('STATUS', colX.status, posY + 6)
       .text('FEE', colX.fee, posY + 6);
  };

  drawTableHeader(y);
  y += 20;

  if (appointments.length === 0) {
    doc.rect(40, y, 515, 40).fillAndStroke('#FFFFFF', borderLight);
    doc.fillColor(textMuted)
       .fontSize(9)
       .font('Helvetica')
       .text('No appointments found matching the specified filter criteria.', 50, y + 15, { align: 'center', width: 495 });
    y += 40;
  } else {
    // 4. Table Rows
    appointments.forEach((apt, idx) => {
      // Check page overflow
      if (y > 740) {
        doc.addPage();
        y = 45;
        drawTableHeader(y);
        y += 20;
      }

      const isEven = idx % 2 === 0;
      doc.rect(40, y, 515, 24).fillAndStroke(isEven ? zebraBg : '#FFFFFF', borderLight);

      doc.fillColor(textDark)
         .fontSize(8)
         .font('Helvetica-Bold')
         .text(`#${apt.appointment_id}`, colX.id, y + 7);

      doc.font('Helvetica-Bold')
         .text(apt.patient_name || 'Patient', colX.patient, y + 4, { width: 105, height: 10, ellipsis: true })
         .font('Helvetica')
         .fillColor(textMuted)
         .fontSize(7)
         .text(apt.patient_email || '', colX.patient, y + 14, { width: 105, height: 9, ellipsis: true });

      doc.fillColor(textDark)
         .fontSize(8)
         .font('Helvetica-Bold')
         .text(apt.doctor_name || 'Dr. Specialist', colX.doctor, y + 4, { width: 110, height: 10, ellipsis: true })
         .font('Helvetica')
         .fillColor(brandTeal)
         .fontSize(7)
         .text(apt.specialization || 'Medicine', colX.doctor, y + 14, { width: 110, height: 9, ellipsis: true });

      const dateStr = apt.appointment_datetime ? new Date(apt.appointment_datetime).toLocaleDateString() : '';
      const timeStr = apt.appointment_datetime ? new Date(apt.appointment_datetime).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) : '';
      doc.fillColor(textDark)
         .fontSize(8)
         .font('Helvetica')
         .text(dateStr, colX.date, y + 4)
         .fillColor(textMuted)
         .fontSize(7)
         .text(timeStr, colX.date, y + 14);

      doc.fillColor(apt.appointment_type === 'VIDEO' ? '#2563EB' : textDark)
         .fontSize(7.5)
         .font('Helvetica')
         .text(apt.appointment_type === 'VIDEO' ? 'Telemedicine' : 'In-Person', colX.type, y + 7);

      const statusColor = apt.status === 'COMPLETED' ? '#059669' : (apt.status === 'CANCELLED' ? '#DC2626' : '#D97706');
      doc.fillColor(statusColor)
         .fontSize(7.5)
         .font('Helvetica-Bold')
         .text(apt.status || 'SCHEDULED', colX.status, y + 7);

      doc.fillColor(textDark)
         .fontSize(8)
         .font('Helvetica-Bold')
         .text(`$${apt.payment_amount || 65.00}`, colX.fee, y + 7);

      y += 24;
    });
  }

  // 5. Total Volume Summary
  const totalRev = appointments
    .filter(a => a.status === 'COMPLETED' || a.payment_status === 'COMPLETED')
    .reduce((sum, a) => sum + (Number(a.payment_amount) || 65), 0);

  if (y > 720) {
    doc.addPage();
    y = 45;
  }

  y += 10;
  doc.rect(40, y, 515, 30).fill(brandNavy);
  doc.fillColor('#FFFFFF')
     .fontSize(9)
     .font('Helvetica-Bold')
     .text(`REPORT SUMMARY: ${appointments.length} Total Appointments Filtered`, 55, y + 10)
     .text(`Completed Consultation Volume: $${totalRev.toFixed(2)}`, 320, y + 10, { align: 'right', width: 220 });

  // 6. Page Numbers in Footer
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    doc.fontSize(7.5)
       .fillColor(textMuted)
       .font('Helvetica')
       .text(
         `HealPoint Clinical Health Systems • Confidential Administration Document • Page ${i + 1} of ${range.count}`,
         40,
         790,
         { align: 'center', width: 515 }
       );
  }

  return doc;
};

